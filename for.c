#include <stdio.h>

int main() {   
   int array[5] = {-2, -7, -3, -4, -5};
    // for (действие, которое выполняется 1 раз в начале цикла ; условие ; действие, которое выполняется в конце каждой итерации )
    for (int i = 0; i < 5; i += 1){
        printf("%d\n", array[i]); // array[i] i - индекс текущей строки и индекс массива, куда записать кол-во
    }
    
    return 0;
}